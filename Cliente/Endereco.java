public class Endereco {
    String logradouro;
    String numero;
    String bairro;
    String cidade;
    String estado;

    Endereco(String logradouro, String numero, String bairro, String cidade, String estado){
        this.logradouro = logradouro;
        this.numero = numero;
        this.bairro = bairro;
        this.cidade = cidade;
        this.estado = estado;
    }
}
